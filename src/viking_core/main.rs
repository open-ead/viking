use std::env::Args;
use std::path::PathBuf;
use std::process::ExitCode;

fn main() -> ExitCode {
    viking::ui::init_logger();
    let mut args = std::env::args();
    let Some(arg0) = args.next() else {
        print_multicall_help();
        return ExitCode::FAILURE;
    };
    let arg0 = PathBuf::from(arg0);
    let Some(exe_name) = arg0.file_stem() else {
        print_multicall_help();
        return ExitCode::FAILURE;
    };
    match run_with_exe_name(exe_name.as_encoded_bytes(), args) {
        Err(e) => {
            eprintln!("fatal: {e:?}");
            ExitCode::FAILURE
        }
        Ok(code) => ExitCode::from(code as u8),
    }
}

#[inline(always)]
fn run_with_exe_name(exe_name: &[u8], args: Args) -> cu::Result<u32> {
    let mut args = match try_multi_call(exe_name, args) {
        Ok(result) => return result,
        Err(x) => x,
    };
    let Some(exe_name) = args.next() else {
        print_multicall_help();
        return Ok(127);
    };
    match try_multi_call_exact(exe_name.as_bytes(), args) {
        Ok(result) => result,
        Err(_) => {
            print_multicall_help();
            Ok(127)
        }
    }
}

// This function is generated by gen-cli.py
#[rustfmt::skip]
#[inline(always)]
fn try_multi_call(exe_name: &[u8], args: Args) -> Result<cu::Result<u32>, Args> {
    if exe_name.ends_with(b"check") {
        return Ok(viking::cli::check_argv(args.collect()));
    }
    if exe_name.ends_with(b"decompme") {
        return Ok(viking::cli::decompme_argv(args.collect()));
    }
    if exe_name.ends_with(b"listsym") {
        return Ok(viking::cli::listsym_argv(args.collect()));
    }
    Err(args)
}

// This function is generated by gen-cli.py
#[rustfmt::skip]
#[inline(always)]
fn try_multi_call_exact(exe_name: &[u8], args: Args) -> Result<cu::Result<u32>, Args> {
    if exe_name == b"check" {
        return Ok(viking::cli::check_argv(args.collect()));
    }
    if exe_name == b"decompme" {
        return Ok(viking::cli::decompme_argv(args.collect()));
    }
    if exe_name == b"listsym" {
        return Ok(viking::cli::listsym_argv(args.collect()));
    }
    Err(args)
}

// This function is generated by gen-cli.py
#[rustfmt::skip]
fn print_multicall_help() {
    eprintln!("NX decomp tools multi-call binary");
    eprintln!("The command that runs depends on the executable name, or call a command directly: viking COMMAND [ARGS...]");
    eprintln!();
    eprintln!("Available commands:");
    eprintln!("  check       Checks if the compiled bytecode of a function matches the assembly found within the game elf.");
    eprintln!("  decompme    Upload a function to decomp.me.");
    eprintln!("  listsym     Print symbols in the output ELF.");
}
